import { NextRequest, NextResponse } from "next/server";

type LabResult = {
  command: string;
  output: string;
  timestamp: string;
  success: boolean;
};

// Simple in-memory storage.
// This is intentionally suitable only for a local demonstration.
// The value will reset whenever the Next.js server restarts.
let latestResult: LabResult | null = null;

/**
 * GET /api/lab-result
 *
 * The dashboard calls this endpoint to retrieve the
 * most recent demonstration result.
 */
export async function GET() {
  return NextResponse.json({
    result: latestResult,
  });
}

/**
 * POST /api/lab-result
 *
 * Stores a result generated by the isolated lab demonstration.
 *
 * This endpoint does NOT execute commands.
 * It only receives text and displays/stores it.
 */
export async function POST(request: NextRequest) {
  try {
    const body = await request.json();

    const command =
      typeof body.command === "string" ? body.command.trim() : "";

    const output =
      typeof body.output === "string" ? body.output : "";

    const success =
      typeof body.success === "boolean" ? body.success : true;

    if (!command || !output) {
      return NextResponse.json(
        {
          error: "Command and output are required.",
        },
        { status: 400 }
      );
    }

    latestResult = {
      command,
      output,
      success,
      timestamp: new Date().toISOString(),
    };

    return NextResponse.json({
      success: true,
      result: latestResult,
    });
  } catch {
    return NextResponse.json(
      {
        error: "Invalid request body.",
      },
      { status: 400 }
    );
  }
}